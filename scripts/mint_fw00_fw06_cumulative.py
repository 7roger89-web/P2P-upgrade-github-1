#!/usr/bin/env python3
"""Build the FW00–FW06 CUMULATIVE self-contained production package candidate (.35).

Two-stage build (spec-compliant):
  Stage A — canonical release packaging via scripts/package_release.py (foundation +
            UI/UX runtime, governance, docs, scripts, skills). All its gates run:
            lineage validation, stage verification, doctor --package, drift.
  Stage B — cumulative system bundle: the tracked .p2p/system tree (p2p_capabilities
            FW02–FW06 modules + tests + capabilities.json, agent skills, scripts,
            release.json, manifest) is copied into the stage under "system/" and
            registered in release-manifest.json + RELEASE-SHA256SUMS.txt.

Principles:
- Deterministic: fixed zip datetimes (2010-01-01), sorted members, DEFLATED.
- Additive: the repo's release assets are never mutated; the only repo write is
  governance/runtime-manifest.lock.json (generated by the canonical build flow,
  same as any package_release run).
- Self-contained: one artifact, foundation runtime + full FW00–FW06 system tree.
- No promotion, no release, no GT/GP/Logistics mutation, no network activity.
"""
import hashlib
import json
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

REPO = Path("/home/ubuntu/fw01_work/auth-f01")
STAGING = REPO / ".tmp" / "fw00-fw06-stage"
OUT_DIR = REPO / "reports" / "candidates"
CANDIDATE_NAME = "P2P-8.4.7-C-Codex-Edition-v24-fw00-fw06-cumulative-candidate.zip"
MANIFEST = "release-manifest.json"
CHECKSUMS = "RELEASE-SHA256SUMS.txt"
SCHEMA = "p2p-codex-release-manifest/1"
FORBIDDEN = ("/.tmp/", "/docs/plans/", "/experimental/", "/.p2p/", "/__pycache__/")
FORBIDDEN_AT_ROOT = ("/reports/")
SYSTEM_EXCLUDE_PREFIXES = ("__pycache__", ".pyc", ".pyo")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def run_build():
    out = STAGING / "foundation.zip"
    if out.exists():
        out.unlink()
    command = [
        sys.executable, str(REPO / "scripts" / "package_release.py"),
        "--root", str(REPO), "--output", str(out),
        "build",
    ]
    result = subprocess.run(command, capture_output=True, text=True, env={
        **dict(__import__("os").environ), "PYTHONDONTWRITEBYTECODE": "1"})
    if result.returncode:
        print("PACKAGE_BUILD_FAILED:\n" + result.stdout[-3000:] + result.stderr[-3000:])
        sys.exit(2)
    print("STAGE_A PASS:", result.stdout.strip().splitlines()[-3:])


def iter_tracked_files(root: Path) -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "-z", str(root)], capture_output=True, text=True, check=True,
        cwd=str(REPO))
    # git ls-files emits paths relative to the repository root
    return sorted(REPO / p for p in result.stdout.split("\0") if p)


def copy_system_bundle(stage: Path) -> list[str]:
    """Stage B: copy the tracked .p2p/system tree into stage/system/."""
    system_root = REPO / ".p2p" / "system"
    dest_root = stage / "system"
    dest_root.mkdir(parents=True, exist_ok=True)
    members = []
    for tracked in iter_tracked_files(system_root):
        relative = tracked.relative_to(system_root)
        rel_posix = relative.as_posix()
        if any(part in SYSTEM_EXCLUDE_PREFIXES for part in relative.parts):
            continue
        dest = dest_root / relative
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(tracked, dest)
        members.append("system/" + rel_posix)
    return members


def extend_manifest(stage: Path, members: list[str]):
    manifest_path = stage / MANIFEST
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    files = list(manifest["files"])
    for rel in members:
        full = stage / rel
        files.append({"path": rel, "size": full.stat().st_size, "sha256": sha256(full)})
    manifest["files"] = files
    manifest["cumulative_scope"] = "FW00-FW06 self-contained production package"
    manifest["cumulative_system_file_count"] = len(members)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
                             encoding="utf-8")

    checksum_path = stage / CHECKSUMS
    lines = []
    listed = {item["path"] for item in manifest["files"]}
    for rel in sorted(listed | {MANIFEST}):
        lines.append(f"{sha256(stage / rel)}  {rel}")
    checksum_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return manifest


def verify_stage(stage: Path, manifest: dict):
    """Cross-check inventory vs actual files (same contract as verify_stage)."""
    listed = {item["path"] for item in manifest["files"]}
    actual = set()
    for full in stage.rglob("*"):
        if full.is_file() and not full.is_symlink():
            actual.add(full.relative_to(stage).as_posix())
    missing = sorted(listed - actual)
    extra = sorted(actual - listed - {MANIFEST, CHECKSUMS})
    assert not missing, f"missing: {missing[:8]}"
    assert not extra, f"extra: {extra[:8]}"
    for item in manifest["files"]:
        full = stage / item["path"]
        assert full.stat().st_size == item["size"], item["path"]
        assert sha256(full) == item["sha256"], item["path"]
    for line in (stage / CHECKSUMS).read_text(encoding="utf-8").splitlines():
        digest, sep, rel = line.partition("  ")
        assert sep and len(digest) == 64, line
        assert sha256(stage / rel) == digest, rel
    for rel in actual:
        norm = "/" + rel
        assert not any(frag in norm for frag in FORBIDDEN), f"forbidden fragment: {rel}"
        if norm.startswith("/reports/"):
            raise AssertionError(f"forbidden root fragment: {rel}")
    print("STAGE_B VERIFICATION PASS")


def write_zip(stage: Path, output: Path):
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists():
        output.unlink()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED,
                         compresslevel=9) as archive:
        for full in sorted(p for p in stage.rglob("*") if p.is_file() and not p.is_symlink()):
            rel = full.relative_to(stage).as_posix()
            info = zipfile.ZipInfo(rel, date_time=(2010, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, full.read_bytes())
    print("ZIP PASS:", output.name, sha256(output), output.stat().st_size, "bytes")


def governance_sanity():
    ctrl = REPO / "governance" / "development-control.json"
    d = json.loads(ctrl.read_text(encoding="utf-8"))
    recs = d["candidate_records"]
    _recs = [r for r in recs if isinstance(r, dict) and r.get("candidate_id")]
    ids = [r["candidate_id"] for r in _recs]
    # GATE-01B identity repair: a single candidate_id may appear EXACTLY
    # twice, and ONLY as a direct numeric successor pair (.35 -> .36)
    # — the successor pins ONE immutable artifact SHA.
    from collections import Counter
    _cnt = Counter(ids)
    for _k, _v in _cnt.items():
        assert _v in (1, 2), f"candidate_id {_k} appears {_v}x (max 2: " \
            "original + one immutable successor)"
        if _v == 2:
            _idxs = [i for i, r in enumerate(_recs) if r["candidate_id"] == _k]
            assert _idxs[1] == _idxs[0] + 1, \
                "successor must be the immediately following record"
            _base, _succ = _recs[_idxs[0]]["candidate_version"], \
                _recs[_idxs[1]]["candidate_version"]
            def _num(v: str):
                return int(v.rsplit(".", 1)[1])
            assert _num(_succ) == _num(_base) + 1, \
                "successor must be the next canonical version number"
            assert _recs[_idxs[0]]["promotion_status"] == "UNPROMOTED" \
                and _recs[_idxs[1]]["promotion_status"] == "UNPROMOTED", \
                "paired duplicates must both be UNPROMOTED"
    for r in recs:
        if isinstance(r, dict) and r.get("candidate_version") in (
                "8.4.7-C-codex.33", "8.4.7-C-codex.34"):
            assert r["promotion_status"] == "UNPROMOTED"
            assert r.get("candidate_id", "")
    print("GOVERNANCE SANITY PASS")


def main():
    if STAGING.exists():
        shutil.rmtree(STAGING)
    run_build()
    foundation_zip = STAGING / "foundation.zip"
    assert foundation_zip.is_file(), "foundation.zip missing after build"
    # Stage B: unpack the canonical foundation into a fresh staging dir.
    stage = STAGING / "stage"
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)
    with zipfile.ZipFile(foundation_zip) as archive:
        for name in archive.namelist():
            dest = stage / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            with archive.open(name) as source, open(dest, "wb") as target:
                target.write(source.read())
    members = copy_system_bundle(stage)
    manifest = extend_manifest(stage, members)
    verify_stage(stage, manifest)
    output = OUT_DIR / CANDIDATE_NAME
    write_zip(stage, output)
    governance_sanity()
    shutil.rmtree(STAGING)
    print("OK — cumulative candidate built at", output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
