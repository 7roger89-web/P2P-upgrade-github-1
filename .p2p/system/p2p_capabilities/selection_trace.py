"""C37 Selection Decision-Trace vocabulary.

Pure vocabulary constants and helpers; NO code paths depend on vendor
names and NO decision text contains hidden reasoning. Every trace entry is
inspectable and deterministic from the recorded evidence.

The canonical vocabulary (no other decision-type strings exist here):
  SELECTION_REQUEST_BUILT            — request revision recorded
  TARGET_EXCLUDED_CAPABILITY         — gate miss (capability-shaped)
  TARGET_EXCLUDED_CERTIFICATION      — gate miss (certification)
  TARGET_EXCLUDED_AUTH               — gate miss (auth fact)
  TARGET_EXCLUDED_PERMISSION         — gate miss (permission profile)
  TARGET_EXCLUDED_QUALITY            — below hard quality floor / failed
  TARGET_EXCLUDED_CONTEXT            — gate miss (context capability)
  TARGET_EXCLUDED_ENVIRONMENT        — gate miss (environment)
  TARGET_EXCLUDED_OWNER_CONSTRAINT   — owner prohibition applied
  TARGET_ELIGIBLE                    — passed every gate
  TARGET_SELECTED                    — selection decision
  MODEL_SELECTED                     — model binding
  REASONING_EFFORT_SELECTED          — effort class binding
  NO_ELIGIBLE_TARGET                 — honest BLOCKED, no eligible set
  RESELECTION_REQUESTED              — structured reselection
  RESELECTION_BLOCKED_MUTATION_UNKNOWN — unknown mutation fail-closed
  RESELECTION_BLOCKED_LOOP           — reselection cap / oscillation guard
"""

