TRACE_SCHEMA = "p2p-selection-trace-c37/1"


def map_exclusion_reason_to_trace(reason: str) -> str:
    """Map a SelectionFilter reason constant to the canonical trace
    decision type. Unknown strings collapse to the generic exclusion
    trace (still a reason constant is NOT invented: reason text travels
    separately in the receipt)."""
    mapping = {
        "TARGET_EXCLUDED_CAPABILITY": TARGET_EXCLUDED_CAPABILITY,
        "TARGET_EXCLUDED_CERTIFICATION": TARGET_EXCLUDED_CERTIFICATION,
        "TARGET_EXCLUDED_AUTH": TARGET_EXCLUDED_AUTH,
        "TARGET_EXCLUDED_PERMISSION": TARGET_EXCLUDED_PERMISSION,
        "TARGET_EXCLUDED_QUALITY": TARGET_EXCLUDED_QUALITY,
        "TARGET_EXCLUDED_CONTEXT": TARGET_EXCLUDED_CONTEXT,
        "TARGET_EXCLUDED_ENVIRONMENT": TARGET_EXCLUDED_ENVIRONMENT,
        "TARGET_EXCLUDED_OWNER_CONSTRAINT": TARGET_EXCLUDED_OWNER_CONSTRAINT,
    }
    return mapping.get(reason, TARGET_EXCLUDED_CAPABILITY)


def selection_request_text(request_id: str, revision: int) -> str:
    return (f"{SELECTION_REQUEST_BUILT}: request {request_id} "
            f"revision {revision}")


